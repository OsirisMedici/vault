from pathlib import Path
import difflib
root=Path('upstream/desktop')
changes={}
def replace(path,old,new,count=1):
    before=changes.get(path,(root/path).read_text(encoding='utf-8'))
    assert before.count(old)==count, (path,old[:70],before.count(old))
    changes[path]=before.replace(old,new)
p='apps/desktop/src/entry.ts'
changes[p]='''// Vault derivative: desktop identity is set before loading services or Keychain namespaces.
import * as path from "path";

import { app } from "electron";

import { DEV_ICON_FILE, isDev } from "./utils";

app.setName("Vault");

// Browser proxy launch is excluded from this isolated macOS candidate.
if (isDev() && process.platform === "darwin") {
  const devIcon = path.join(__dirname, "images", DEV_ICON_FILE);
  void app.whenReady().then(() => app.dock.setIcon(devIcon));
}

// eslint-disable-next-line @typescript-eslint/no-require-imports
const Main = require("./main").Main;
const main = new Main();
main.bootstrap();
'''
p='apps/desktop/src/main.ts'
s=(root/p).read_text()
start=s.index('    // Set paths for portable builds')
end=s.index('\n    app.on("ready"',start)
changes[p]=s[:start]+'''    // Vault uses its own profile and never reads the official client's app-data override.
    const appDataPath = path.join(app.getPath("appData"), "Vault");
'''+s[end:]
s=changes[p]; start=s.index('        app.removeAsDefaultProtocolClient("bitwarden");'); end=s.index('        // Process protocol for macOS',start)
changes[p]=s[:start]+'''        // Shared bitwarden:// registration stays with the official client.
        // Vault browser/SSO callbacks need a separately reviewed integration.

'''+s[end:]
p='apps/desktop/src/main/updater.main.ts'
s=(root/p).read_text()
start=s.index('  private userDisabledUpdates(): boolean {')
changes[p]=s[:start]+'''  private userDisabledUpdates(): boolean {
    // Vault has no reviewed update feed. Never fetch or install upstream releases.
    return true;
  }
}
'''
p='apps/desktop/src/main/native-messaging.main.ts'
replace(p,'export class NativeMessagingMain {','''export class NativeMessagingMain {
  // Keep official browser manifests and sockets untouched, including remove calls.
  private readonly vaultBrowserIntegrationDisabled = true;''')
for signature in ['async listen()', 'async generateManifests()', 'async generateDdgManifests()', 'async removeManifests()', 'async removeDdgManifests()']:
    replace(p,'  '+signature+' {','  '+signature+' {\n    if (this.vaultBrowserIntegrationDisabled) {\n      return;\n    }')
replace('apps/desktop/src/index.html','<title>Bitwarden</title>','<title>Vault</title>')
replace('apps/desktop/src/package.json','"name": "@bitwarden/desktop"','"name": "vault"')
replace('apps/desktop/src/package.json','"productName": "Bitwarden"','"productName": "Vault"')
replace('apps/desktop/src/package.json','"desktopName": "bitwarden.desktop"','"desktopName": "vault.desktop"')
replace('apps/desktop/src/package.json','"homepage": "https://bitwarden.com"','"homepage": "https://github.com/OsirisMedici/vault"')
replace('apps/desktop/src/package.json','"url": "git+https://github.com/bitwarden/clients.git"','"url": "git+https://github.com/OsirisMedici/vault.git"')
# Product label in every translation is generated by prepare-desktop.py, not wholesale copy replacement.
patch=[]
for path,new in changes.items():
    old=(root/path).read_text(encoding='utf-8')
    patch.extend(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile='a/'+path,tofile='b/'+path))
Path('branding/desktop/source.patch').write_text(''.join(patch))
